        ["Severe-late rate (> 7 days)", f"{pct(o['severe_rate'])} ({n(o['n_severe'])})", ci(*o['severe_ci'])],
        ["Severe orders as share of late orders", pct(o['severe_share_of_late'], 1), ""],
        ["Median lead time", f"{lo_['median']:.2f} days", f"[{lo_['median_ci'][0]:.2f}, {lo_['median_ci'][1]:.2f}]"],
        ["p90 lead time", f"{lo_['p90']:.2f} days", f"[{lo_['p90_ci'][0]:.2f}, {lo_['p90_ci'][1]:.2f}]"],
        ["p95 lead time", f"{lo_['p95']:.2f} days", f"[{lo_['p95_ci'][0]:.2f}, {lo_['p95_ci'][1]:.2f}]"],
        ["Median promised lead time", f"{ps['promised_lead_median']:.0f} days", ""],
