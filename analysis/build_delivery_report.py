      "(c) The high-volume group is heterogeneous: " + hv_detail + " "
      "Months with similar volume (2018-06 to 2018-08) had very different late rates, and 2018-02, the second-highest late rate, is not in the high-volume group. Volume alone does not explain the episodes. "
