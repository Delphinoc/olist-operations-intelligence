    A(f"**[Observed]** About {pct(o['late_rate'], 1)} of delivered orders arrive after the promised calendar date and {pct(o['severe_rate'], 1)} arrive more than a week late. "
      f"The pooled rate hides large month-to-month variation: cohort rates range from {pct(o['late_rate_min_month'], 1)} to {pct(o['late_rate_max_month'], 1)} (Section 3).\n")

    # ------------------------------------------------------------------ 3
    A("## 3. Late rate by purchase-month cohort\n")
    A("![Monthly late rate](figures/delivery_01_monthly_late_rate.png)\n")
