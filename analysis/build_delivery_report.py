    A("## 5. Promise error and earliness\n")
    A("![Promise error](figures/delivery_03_promise_error_distribution.png)\n")
    A(f"**[Observed]** The median order arrives **{abs(ps['error_p50']):.0f} days before** the promised date (p25 {ps['error_p25']:.0f}, p75 {ps['error_p75']:.0f}; p5 {ps['error_p05']:.0f}, p95 {ps['error_p95']:.0f}). "
      f"{pct(ps['n_before_promised_day'] / ps['n_delivered'], 1)} of delivered orders arrive before the promised day, {pct(ps['n_on_promised_day'] / ps['n_delivered'], 1)} on it, "
      f"{pct(ps['n_7plus_days_early'] / ps['n_delivered'], 1)} at least 7 days early and {pct(ps['n_14plus_days_early'] / ps['n_delivered'], 1)} at least 14 days early. "
      f"Among on-time orders the median slack is {ps['slack_median_on_time']:.0f} days (interquartile range {ps['slack_p25_on_time']:.0f} to {ps['slack_p75_on_time']:.0f}). "
      f"The median order takes {pct(ps['lead_to_promise_ratio_median'], 0)} of its promised lead time.\n")
    A("**[Interpretation]** Estimated delivery dates carry a large buffer for typical orders. The same buffer is not enough in the episodic late cohorts: the promised-lead mix was stable "
      f"across months (expected late rate given the mix stays between {pct(m.expected_rate.iloc[3:].min(), 1)} and {pct(m.expected_rate.iloc[3:].max(), 1)} from 2017-04 onward, Figure 6), "
      "so promises did not become more conservative when deliveries slowed.\n")

