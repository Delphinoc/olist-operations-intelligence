    for t, (grain, key, note) in grains.items():
        n = q1(f"SELECT count(*) FROM {t}")
        ncol = q1(f"SELECT count(*) FROM information_schema.columns WHERE table_name = '{t}'")
        rows.append([f"`{t}`", grain, key, n, ncol, note])
    w(md_table(["Table / view", "Grain (one row per)", "Primary key", "Rows", "Cols", "Notes"], rows))
    w("\nStaging tables (typed copies of the raw CSVs): " + ", ".join(
        f"`{t}` ({q1(f'SELECT count(*) FROM {t}'):,})" for (t,) in q(
            "SELECT table_name FROM information_schema.tables WHERE table_name LIKE 'stg_%' ORDER BY 1")) + ".\n")
    w("Columns of `fact_orders`: " + ", ".join(f"`{c}`" for (c,) in q(
        "SELECT column_name FROM information_schema.columns WHERE table_name = 'fact_orders' ORDER BY ordinal_position")) + ".\n")
