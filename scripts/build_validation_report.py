        ["Orders by `order_category` type", "", ", ".join(f"{k} {v:,}" for k, v in q("SELECT CASE WHEN order_category IN ('mixed','unknown') THEN order_category WHEN order_category IS NULL THEN 'no items' ELSE 'single category' END k, count(*) FROM fact_orders GROUP BY 1 ORDER BY 2 DESC"))],
