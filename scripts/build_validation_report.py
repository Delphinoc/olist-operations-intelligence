RAW = build_model.DEFAULT_RAW
OUT = ROOT / "reports" / "data_model_validation.md"
JUNIT = ROOT / "data" / "processed" / "pytest_junit.xml"


def md_table(headers: list[str], rows: list[list]) -> str:
    def fmt(v):
        if isinstance(v, float):
            return f"{v:,.4f}"
        if isinstance(v, int):
            return f"{v:,}"
        return str(v)
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def run_pytest() -> tuple[int, list[tuple[str, str, float]], str]:
    JUNIT.parent.mkdir(parents=True, exist_ok=True)
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", f"--junitxml={JUNIT}"], cwd=ROOT,
                          capture_output=True, text=True)
    cases = []
    for tc in ET.parse(JUNIT).getroot().iter("testcase"):
        status = "FAIL" if (tc.find("failure") is not None or tc.find("error") is not None) else (
            "SKIP" if tc.find("skipped") is not None else "PASS")
        cases.append((tc.get("name"), status, float(tc.get("time", 0))))
    summary = proc.stdout.strip().splitlines()[-1] if proc.stdout.strip() else "(no output)"
    return proc.returncode, cases, summary


def main() -> int:
    if not DB.exists():
        print("Model not found. Run: python scripts/build_model.py", file=sys.stderr)
        return 1
    con = duckdb.connect(str(DB), read_only=True)
    q = lambda sql: con.execute(sql).fetchall()      # noqa: E731
    q1 = lambda sql: con.execute(sql).fetchone()[0]  # noqa: E731

    rc, cases, pytest_summary = run_pytest()
    ref = reference_pandas.compute_reference(RAW)
    build_results = build_model.build(RAW, ROOT / "data" / "processed" / "_report_rebuild.duckdb", verbose=False)
    (ROOT / "data" / "processed" / "_report_rebuild.duckdb").unlink(missing_ok=True)

    P = dict(zip(["window_start", "window_end_exclusive", "severe_late_days", "reference_date"],
                 q("SELECT window_start, window_end_exclusive, severe_late_days, reference_date FROM model_params")[0]))
    out: list[str] = []
    w = out.append

    w("# Data Model Validation Report (Phase 1)\n")
    w("Generated by `scripts/build_validation_report.py` from the DuckDB model built by `scripts/build_model.py` "
      "(SQL in `sql/`). Raw CSVs in `data/raw/` are read-only and were hash-checked unchanged by the test suite. "
      "Analytical data model only: no EDA, hypothesis tests, seller rankings, dashboard or ML were performed.\n")
    w(f"Model parameters: window = purchases {P['window_start']} to before {P['window_end_exclusive']} "
      f"(2017-01 to 2018-08); severe lateness = promise error > {P['severe_late_days']} calendar days; "
      f"reference date = {P['reference_date']} (latest observed event timestamp in the extract).\n")

    overall = "PASS" if rc == 0 else "FAIL"
