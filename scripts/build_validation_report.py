"""Generate reports/data_model_validation.md from the built DuckDB model.

Usage (after `python scripts/build_model.py`):
    python scripts/build_validation_report.py

Every number in the tables is queried from the model, recomputed with the independent pandas reference,
or taken from the pytest run executed by this script. Narrative sections (deviations, issues) are static
text written after inspecting those results.
"""
